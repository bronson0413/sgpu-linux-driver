/* Print the syzkaller constants from the real headers, so they cannot drift. */
#include <stdio.h>
#include "sgpu_uapi.h"

#define P(x) printf(#x " = %llu\n", (unsigned long long)(x))

int main(void)
{
	puts("# Generated by scripts/gen_syz_const.c");
	puts("arches = amd64");
	P(SGPU_IOC_INFO);
	P(SGPU_IOC_BO_CREATE);
	P(SGPU_IOC_BO_DESTROY);
	P(SGPU_IOC_BO_WRITE);
	P(SGPU_IOC_BO_READ);
	P(SGPU_IOC_SUBMIT);
	P(SGPU_IOC_WAIT);
	P(SGPU_OP_NOP);
	P(SGPU_OP_FILL);
	P(SGPU_OP_COPY);
	P(SGPU_OP_TEST_HANG);
	P(SGPU_OP_TEST_FAULT);
	puts("AT_FDCWD = 18446744073709551516");
	return 0;
}
